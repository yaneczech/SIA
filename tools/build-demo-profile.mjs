#!/usr/bin/env node
/**
 * Builds the browser-importable demo profile from normative and executable
 * repository artifacts. The generated module is committed so the static demo
 * works without a build step; --check makes drift a test failure.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { canonicalSha256 } from './canonical.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const readJson = async (...parts) => JSON.parse(await readFile(path.join(root, ...parts), 'utf8'));
const catalog = await readJson('examples', 'v0.4', 'catalog.json');
const contextPolicy = await readJson('examples', 'v0.4', 'core.context-policy.json');
const instanceSchema = await readJson('schema', 'runtime-instance.schema.json');
const contextSchema = await readJson('schema', 'context-snapshot.schema.json');
const rendererFiles = ['cluster.renderer.json', 'ivi.renderer.json', 'voice.renderer.json'];
const renderers = await Promise.all(rendererFiles.map((file) => readJson('examples', 'v0.4', file)));
const exampleFiles = [
  'actor-registry.json', 'collision-warning.instance.json', 'context-attentive.json',
  'now-playing.retention-record.json', 'collision.render-plan.json', 'collision.dispatch-attempt.json',
  'collision.delivery-receipt.json', 'collision.occupant-response.json', 'collision.audit-record.json',
];
const examples = Object.fromEntries(await Promise.all(exampleFiles.map(async (file) => [file, await readJson('examples', 'v0.4', file)])));

const actorClasses = instanceSchema.$defs.attestation.properties.actor_class.enum;
const contextAxes = Object.keys(contextSchema.properties.axes.properties);
const nodes = catalog.nodes.map((declaration) => ({
  declaration,
  declaration_sha256: canonicalSha256(declaration),
}));
const withoutSignature = (evidence) => {
  if (!evidence) return evidence;
  const { signature, ...rest } = evidence;
  return rest;
};
const collisionNode = catalog.nodes.find((node) => node.id === 'Interaction.Event.Alert.Collision.Warning');
const instance = examples['collision-warning.instance.json'];
const context = examples['context-attentive.json'];
const plan = examples['collision.render-plan.json'];
const attempt = examples['collision.dispatch-attempt.json'];
const receipt = examples['collision.delivery-receipt.json'];
const response = examples['collision.occupant-response.json'];
const retention = examples['now-playing.retention-record.json'];
const audit = examples['collision.audit-record.json'];
const registry = examples['actor-registry.json'];
const docExcerpts = {
  catalog: { spec_version: catalog.spec_version, profile_id: catalog.profile_id, profile_version: catalog.profile_version, catalog_version: catalog.catalog_version, generated_at_ms: catalog.generated_at_ms, nodes: catalog.nodes.map(({ id, priority }) => ({ id, priority })), integrity: withoutSignature(catalog.integrity) },
  registry: { spec_version: registry.spec_version, profile_id: registry.profile_id, registry_version: registry.registry_version, credentials: registry.credentials, integrity: withoutSignature(registry.integrity) },
  policy: { spec_version: contextPolicy.spec_version, policy_id: contextPolicy.policy_id, policy_version: contextPolicy.policy_version, axis_requirements: contextPolicy.axis_requirements, attention_modifiers: contextPolicy.attention_modifiers, integrity: withoutSignature(contextPolicy.integrity) },
  node: collisionNode,
  instance: { ...instance, attestation: withoutSignature(instance.attestation) },
  context: { ...context, integrity: withoutSignature(context.integrity) },
  renderer: { ...renderers[0], attestation: withoutSignature(renderers[0].attestation) },
  retention,
  plan,
  dispatch: { ...attempt, integrity: withoutSignature(attempt.integrity) },
  receipt: { ...receipt, attestation: withoutSignature(receipt.attestation) },
  response: { ...response, evidence: withoutSignature(response.evidence) },
  audit,
};

const header = `// Generated by tools/build-demo-profile.mjs. Do not edit by hand.\n`;
const emit = (name, value) => `export const ${name} = Object.freeze(${JSON.stringify(value, null, 2)});\n\n`;
const output = (header
  + emit('PROFILE_META', {
    spec_version: catalog.spec_version,
    profile_id: catalog.profile_id,
    profile_version: catalog.profile_version,
    catalog_version: catalog.catalog_version,
    catalog_sha256: canonicalSha256(catalog),
  })
  + emit('ACTOR_CLASS_IDS', actorClasses)
  + emit('CONTEXT_AXES', contextAxes)
  + emit('CONTEXT_POLICY', contextPolicy)
  + emit('NODE_RECORDS', nodes)
  + emit('RENDERER_DECLARATIONS', renderers)
  + emit('DOC_EXCERPTS', docExcerpts)).trimEnd() + '\n';

const outputFile = path.join(root, 'demo', 'generated-profile.js');
if (process.argv.includes('--check')) {
  const current = await readFile(outputFile, 'utf8').catch(() => '');
  if (current !== output) {
    console.error('demo/generated-profile.js is stale; run npm run build:demo-profile');
    process.exitCode = 1;
  }
} else {
  await writeFile(outputFile, output);
  console.log('✓ demo/generated-profile.js refreshed from canonical artifacts');
}
